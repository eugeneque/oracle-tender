# Обратный указатель «поле → его группа». Нужен, когда модель кладёт известное поле не в ту
# группу: «Максимальный ток» приходил в «Интерфейсы и связь», «Номинальное напряжение» — в
# «Конструктивные характеристики». Значение при этом верное, терять его незачем.
_GROUP_NAMES: frozenset[str] = frozenset(name.casefold() for name in CHARACTERISTIC_GROUPS)

_GROUP_OF_FIELD: dict[str, str] = {
    field.casefold(): group for group, fields in CHARACTERISTIC_GROUPS.items() for field in fields
}


def resolve_field(group_name: str, field_name: str) -> tuple[str, str] | None:
    """Приводит ответ модели к паре «группа справочника, поле справочника».

    `None` — характеристику опознать не удалось, её место в `extra_specifications`, а не в
    схеме Приложения C. Порядок разбора: как есть → синоним → без приставки-группы → снова
    синоним. Группа берётся из справочника: она однозначно определяется полем.
    """

    field = (field_name or "").strip()
    if not field:
        return None
    # Название группы вместо имени поля — заголовок раздела документа, а не характеристика.
    # Проверяется до всего остального: иначе «Протоколы обмена» уехало бы в «Прочие протоколы».
    if field.casefold() in _GROUP_NAMES:
        return None

    for candidate in _field_candidates(field):
        key = candidate.casefold()
        target = FIELD_SYNONYMS.get(key)
        if target is not None:
            return _GROUP_OF_FIELD[target.casefold()], target
        group = _GROUP_OF_FIELD.get(key)
        if group is not None:
            # Имя поля совпало со справочником — группу берём его, а не ту, что назвала
            # модель: поле «Максимальный ток» принадлежит электрическим характеристикам,
            # в какую бы группу его ни положили.
            return group, next(
                name for name in CHARACTERISTIC_GROUPS[group] if name.casefold() == key
            )

    # Уточнённая формулировка известного поля: «Класс точности при измерении активной энергии
    # в двух направлениях» — это класс точности, и терять значение из-за приписки незачем.
    lowered = field.casefold()
    for known, group in _GROUP_OF_FIELD.items():
        if len(known) >= 10 and lowered.startswith(known):
            return group, next(
                name for name in CHARACTERISTIC_GROUPS[group] if name.casefold() == known
            )

    # Название конкретного протокола в группе протоколов: «Протокол обмена Пульсар»,
    # «Протокол ГОСТ Р МЭК 62056-21». Справочник перечисляет распространённые протоколы
    # поимённо, а для прочих держит отдельное поле — туда такие и попадают.
    if group_name.casefold() == "протоколы обмена" and lowered.startswith("протокол"):
        return "Протоколы обмена", "Прочие протоколы"
    return None


def _field_candidates(field: str) -> list[str]:
    """Варианты написания поля: как пришло и без приставки-названия группы."""

    candidates = [field]
    lowered = field.casefold()
    for prefix in _GROUP_PREFIXES:
        if lowered.startswith(prefix) and len(field) > len(prefix) + 1:
            trimmed = field[len(prefix) :].lstrip(" :-—").strip()
            if trimmed:
                candidates.append(trimmed)
    return candidates
