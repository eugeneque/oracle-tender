PARAMETERS_BY_NO: dict[int, MeterParameter] = {item.no: item for item in METER_PARAMETERS}


def detect_parameter(text: str | None) -> int | None:
    """Номер параметра по формулировке требования — для требований, у которых модель его
    не поставила. Только параметры с правилами кода и узнаваемыми формулировками: для
    прочих ошибиться дешевле, чем угадать неверно."""

    if not text:
        return None
    for item in METER_PARAMETERS:
        if item.rule and any(pattern.search(text) for pattern in item.patterns):
            return item.no
    return None


def parameters_prompt_list() -> str:
    """Перечень для промпта извлечения: «N. Название — комментарий»."""

    lines = []
    for item in METER_PARAMETERS:
        line = f"{item.no}. {item.name}"
        if item.note:
            line += f" — {item.note}"
        lines.append(line)
    return "\n".join(lines)


def parameter_hint(no: int | None) -> str:
    """Подпись к требованию в запросе на сопоставление: параметр и правило файла."""

    item = PARAMETERS_BY_NO.get(no or 0)
    if item is None:
        return ""
    hint = f"[параметр {item.no}: {item.name}"
    if item.note:
        hint += f"; правило: {item.note}"
    return hint + "]"
