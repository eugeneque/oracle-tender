"""Параметры для приборов учёта — файл тендерного отдела «Параметры для ПУ.xlsx»
(лист «ПУ сплит (одноф.)», передан 25.09.2026).

Это перечень того, что тендерный отдел проверяет в техническом задании на прибор учёта,
с комментариями — как параметр трактовать. Он используется в двух местах:

* **извлечение требований** (`tender_analysis`) — модель получает перечень и у каждого
  требования к товару указывает номер параметра (`Requirement.parameter_no`); требования
  раскладываются по одной сетке у всех закупок, а не формулировками конкретного ТЗ;
* **сопоставление** (`compliance_service`) — у каждого требования в запросе стоит его
  параметр и правило из комментария файла; часть правил выполняет код (см. `rule`).

Комментарии файла перенесены в `note` почти дословно — это указания тендерного отдела,
и расходиться с ними в пересказе нельзя. Если файл обновится, правится этот модуль,
а не промпты.

`fields` — поля справочника характеристик (Приложение C), где у модели каталога лежит
ответ на параметр: по ним сопоставление ищет факты, а человек — куда дописать значение.
`patterns` — по каким словам параметр узнаётся в тексте требования, если модель при
извлечении номер не поставила (старые требования, ручные правки): правила, которые
выполняет код, не должны зависеть от того, заполнила ли модель поле.
"""

