"""Документация закупки из ЕИС по её реестровому номеру — общий запасной путь для всех
площадок (раздел 5.2 ТЗ).

**Почему это работает.** Закупки по 44-ФЗ и 223-ФЗ публикуются в Единой информационной
системе независимо от того, на какой электронной площадке они проводятся: это требование
закона, а не любезность площадки. Реестровый номер закупки — общий ключ, и по нему карточка
в ЕИС отдаёт тот же комплект документации, что и личный кабинет площадки.

**Зачем это нужно.** У части площадок документы вообще не показываются анонимному
посетителю: Lot-online отдаёт карточку без единого файла, Росэлторг закрывает доступ
антибот-защитой, у Сбербанк-АСТ файлы живут за авторизацией. Без этого модуля закупки
оттуда остались бы без документов — а значит, без ИИ-анализа требований и без процента
победителя, то есть бесполезными для работы.

Родной разбор площадки всё равно остаётся первым: на площадке публикуются разъяснения и
приложения, которых в ЕИС может не быть, а у коммерческих закупок (без номера ЕИС) другого
источника документов нет вовсе.
"""

from __future__ import annotations

import re

import httpx
from loguru import logger

from app.adapters.base import DocumentRef


class EisUnavailableError(RuntimeError):
    """ЕИС не ответил: сеть, таймаут, сброс соединения, HTTP-ошибка.

    Отличается от «в ЕИС нет такой закупки» намеренно. Пустой список документов означает
    «документов нет», и после него анализ честно сообщает «требований не найдено» — а когда
    zakupki.gov.ru просто сбросил соединение (так он отвечает с иностранных адресов, из-под
    VPN), это ложь: документы есть, их не удалось получить. Человек должен видеть именно
    вторую формулировку, иначе он идёт искать несуществующее ТЗ вместо того, чтобы отключить
    VPN и запустить анализ ещё раз.
    """

# Реестровые номера: 19 цифр у 44-ФЗ, 11 цифр у 223-ФЗ. Номера площадок (`ПИ602053`,
# `SBR003-260002867000007.1`, `АП123145`) под эти шаблоны не подходят и в ЕИС не найдутся —
# ходить туда за ними бессмысленно.
_EIS_NUMBER = re.compile(r"^(\d{19}|\d{11})$")


def normalize_eis_number(external_id: str | None) -> str | None:
    """Реестровый номер ЕИС из идентификатора площадки либо `None`.

    Часть площадок добавляет к номеру суффикс лота (`32110674684.lot1` у Lot-online) —
    в ЕИС закупка числится без него.
    """

    if not external_id:
        return None

    candidate = external_id.strip()
    # Отрезаем суффикс лота: `.lot1`, `-1`, `.1` — но только если без него остаётся номер.
    for separator in (".lot", "."):
        head = candidate.split(separator, 1)[0]
        if _EIS_NUMBER.match(head):
            return head

    return candidate if _EIS_NUMBER.match(candidate) else None


def fetch_eis_documents(external_id: str | None) -> list[DocumentRef]:
    """Документы закупки из ЕИС. Пустой список — если номер не реестровый или в ЕИС нет
    карточки с таким номером: это запасной путь, и «не нашлось» не должно выглядеть как
    сбой самой площадки. Сетевой отказ ЕИС — другое дело, он поднимается наружу как
    `EisUnavailableError`: вызывающий код обязан сказать человеку, что документы не
    получены, а не что их нет."""

    number = normalize_eis_number(external_id)
    if number is None:
        return []

    # Импорт внутри функции: `eis` импортирует общие утилиты адаптеров, и вынос импорта
    # наверх замкнул бы цикл, когда сам ЕИС начнёт пользоваться этим модулем.
    from app.adapters.eis import EisAdapter

    try:
        return EisAdapter().download_documents(number)
    except httpx.HTTPError as exc:
        logger.warning(f"Документы закупки {number} не получены из ЕИС: {exc}")
        raise EisUnavailableError(f"ЕИС не ответил: {exc}") from exc
    except Exception as exc:  # noqa: BLE001 - запасной путь: не нашлось — просто нет документов
        logger.warning(f"Документы закупки {number} не найдены в ЕИС: {exc}")
        return []
